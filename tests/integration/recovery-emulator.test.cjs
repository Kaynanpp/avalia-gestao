const { test } = require('node:test');
const assert = require('node:assert/strict');
const { randomBytes, createHmac, createHash } = require('node:crypto');
const { initializeApp, deleteApp } = require('firebase-admin/app');
const { getFirestore, Timestamp, GeoPoint } = require('firebase-admin/firestore');
const { getAuth } = require('firebase-admin/auth');
const { capture, seal, unseal, restoreEmptyEmulator } = require('../../scripts/portable-backup.cjs');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

test('encrypted backup restores Firestore types, Auth and functional HTTP flows into an empty isolated destination', { timeout: 600000 }, async (t) => {
  assert.match(process.env.FIRESTORE_EMULATOR_HOST || '', /^127\.0\.0\.1:\d+$/);
  assert.match(process.env.FIREBASE_AUTH_EMULATOR_HOST || '', /^127\.0\.0\.1:\d+$/);
  const source = initializeApp({ projectId: 'demo-backup-source' }, 'backup-source');
  const destination = initializeApp({ projectId: 'demo-avalia-gestao' }, 'backup-destination');
  t.after(async () => { await deleteApp(source); await deleteApp(destination); });
  const db = getFirestore(source), auth = getAuth(source), restored = getFirestore(destination);
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'avalia-recovery-'));
  const file = path.join(directory, 'backup.enc');
  const key = randomBytes(32), now = Timestamp.now();
  const password = 'RecoveryOnly1!';
  await auth.createUser({ uid: 'recovery-admin', email: 'recovery@example.invalid', password });
  const batch = db.batch();
  const put = (collection, id, data) => batch.set(db.collection(collection).doc(id), { createdAt: now, updatedAt: now, ...data });
  put('users', 'recovery-admin', { email: 'recovery@example.invalid', name: 'Conta de recuperação fictícia', role: 'ADMIN', active: true, mustChangePassword: false });
  put('departments', 'recovery-sector', { name: 'Produção fictícia', active: true });
  put('managers', 'recovery-leader', { name: 'Liderança fictícia', departmentId: 'recovery-sector', departmentName: 'Produção fictícia', position: 'Líder', status: 'ACTIVE' });
  for (let i = 1; i <= 6; i++) put('coworkers', `recovery-person-${i}`, { name: `Colega fictício ${i}`, registration: `RC00${i}`, registrationNormalized: `RC00${i}`, departmentId: 'recovery-sector', departmentName: 'Produção fictícia', position: 'Operador', active: true });
  put('evaluationPeriods', 'recovery-cycle', { name: 'Ciclo de recuperação', status: 'OPEN', startDate: new Date(Date.now() - 86400000), endDate: new Date(Date.now() + 86400000), modalities: ['LEADERSHIP', 'PEER'], leadershipParticipationRequired: true });
  put('criteria', 'recovery-criterion', { name: 'Colaboração', description: 'Critério fictício', active: true, order: 1, modality: 'BOTH' });
  put('settings', 'app', { companyName: 'Empresa fictícia', appName: 'Avalia Gestão', minEvaluationsForDisplay: 5, commentsEnabled: true });
  const hash = (value) => createHmac('sha256', createHash('sha256').update(process.env.PARTICIPATION_SECRET).digest()).update(value).digest('hex');
  for (let i = 1; i <= 5; i++) {
    put('evaluations', `historical-${i}`, { managerId: 'recovery-leader', periodId: 'recovery-cycle', evaluationType: 'TEAM', answers: [{ criterionId: 'recovery-criterion', criterionName: 'Colaboração', score: i }], overallScore: i, comment: 'Comentário fictício preservado', participationVerified: true });
    // Do not include high-resolution times or a response reference in participation.
    batch.set(db.collection('leadershipParticipation').doc(hash(`leadership-pair:recovery-cycle:recovery-person-${i}:recovery-leader`)), { periodId: 'recovery-cycle', departmentId: 'recovery-sector', completedDate: new Date().toISOString().slice(0, 10), participantHash: hash(`person:recovery-person-${i}`) });
  }
  put('developmentPlans', 'recovery-plan', { managerId: 'recovery-leader', periodId: 'recovery-cycle', title: 'Plano fictício', status: 'OPEN' });
  put('recoveryTypes', 'edge-values', { instant: new Timestamp(1730000000, 123456789), point: new GeoPoint(-20, -45), bytes: Buffer.from('fixture'), reference: db.doc('managers/recovery-leader'), nested: [{ type: 'timestamp', value: 'ordinary-map' }], nan: NaN, infinity: Infinity });
  batch.set(db.doc('missing-parent/absent/children/child'), { preserved: true });
  await batch.commit();
  const start = Date.now();
  const backup = await capture(db, auth, 'demo-backup-source');
  fs.writeFileSync(file, seal(backup, key), { mode: 0o600, flag: 'wx' });
  const encrypted = fs.readFileSync(file, 'utf8');
  assert.ok(!encrypted.includes('recovery@example.invalid'));
  assert.throws(() => unseal(encrypted, randomBytes(32)));
  const damaged = JSON.parse(encrypted); damaged.content = 'AAAA' + damaged.content.slice(4);
  assert.throws(() => unseal(JSON.stringify(damaged), key));
  const exportDurationMs = Date.now() - start;
  const recoveryStart = Date.now();
  await restoreEmptyEmulator(restored, getAuth(destination), unseal(encrypted, key));
  const verification = await capture(restored, getAuth(destination), 'demo-avalia-gestao');
  assert.equal(verification.documentDigest, backup.documentDigest);
  assert.deepEqual(verification.users.map((u) => u.uid), backup.users.map((u) => u.uid));
  assert.equal((await restored.doc('missing-parent/absent/children/child').get()).data().preserved, true);
  assert.ok((await restored.doc('recoveryTypes/edge-values').get()).data().instant.isEqual((await db.doc('recoveryTypes/edge-values').get()).data().instant), 'Preservar a precisão retornada pelo Firestore, que normaliza o armazenamento em microssegundos.');
  assert.equal((await restored.collection('evaluations').get()).size, 5);
  assert.equal((await restored.collection('leadershipParticipation').get()).size, 5);
  assert.equal((await restored.doc('developmentPlans/recovery-plan').get()).data().managerId, 'recovery-leader');
  await assert.rejects(() => restoreEmptyEmulator(restored, getAuth(destination), backup), /vazio/);
  const base = process.env.TEST_APP_URL;
  const call = (route, body, cookie) => fetch(base + route, { method: body ? 'POST' : 'GET', headers: { ...(body ? { 'Content-Type': 'application/json' } : {}), ...(cookie ? { Cookie: cookie } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}), signal: AbortSignal.timeout(120000) });
  const login = await call('/api/admin/login', { email: 'recovery@example.invalid', password });
  assert.equal(login.status, 200, 'A senha original precisa funcionar depois de importar Auth.');
  const cookie = login.headers.get('set-cookie').split(';')[0];
  assert.equal((await call('/api/admin/usuarios', undefined, cookie)).status, 200);
  const report = await call('/admin/relatorios?periodo=recovery-cycle', undefined, cookie);
  assert.equal(report.status, 200);
  assert.ok((await report.text()).includes('Liderança fictícia'));
  const contextResponse = await call('/api/avaliacoes/acesso', { registration: 'RC006' });
  assert.equal(contextResponse.status, 200);
  const context = (await contextResponse.json()).data;
  const body = { managerId: 'recovery-leader', periodId: context.period.id, evaluationType: 'TEAM', participationToken: context.participationToken, answers: context.criteria.map((c) => ({ criterionId: c.id, score: 4 })) };
  assert.equal((await call('/api/avaliacoes', body)).status, 201);
  assert.equal((await call('/api/avaliacoes', body)).status, 409);
  const previous = (await (await call('/api/avaliacoes/acesso', { registration: 'RC001' })).json()).data;
  assert.equal((await call('/api/avaliacoes', { ...body, participationToken: previous.participationToken })).status, 409, 'A participação anterior ao backup precisa continuar bloqueando duplicidade.');
  assert.equal((await call('/api/admin/relatorios/export?periodo=recovery-cycle', undefined, cookie)).status, 200);
  assert.equal((await call('/api/ready')).status, 200);
  const result = { documents: backup.documents.length, users: backup.users.length, exportDurationMs, restoreAndFunctionalCheckMs: Date.now() - recoveryStart, backupBytes: fs.statSync(file).size, productionTouched: false };
  console.log('RECOVERY_RESULT ' + JSON.stringify(result));
  // Keep only aggregate evidence in the repository; fixture backup stays outside it.
  fs.mkdirSync(path.resolve('artifacts'), { recursive: true });
  fs.writeFileSync(path.resolve('artifacts/recovery-result.json'), JSON.stringify(result, null, 2));
});
